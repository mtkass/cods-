# Для этого построим корреляционную матрицу между месяцами на основе
# многолетних данных. Это позволит выявить, существуют ли устойчивые
# связи между количеством терактов в разные месяцы.

import pandas as pd
import seaborn as sns
import matplotlib.pyplot as plt
import numpy as np

# Получаем данные по годам и месяцам
cur.execute("""
    SELECT iyear, imonth, COUNT(*) as cnt
    FROM terrorist_attacks
    GROUP BY iyear, imonth
    ORDER BY iyear, imonth;
""")
data = cur.fetchall()

# Преобразуем в DataFrame
df = pd.DataFrame(data, columns=['year', 'month', 'count'])

# Строим сводную таблицу: годы → строки, месяцы → столбцы
pivot = df.pivot(index='year', columns='month', values='count').fillna(0)

# Вычисляем матрицу корреляций Пирсона между месяцами
corr = pivot.corr()

# Визуализация тепловой карты
plt.figure(figsize=(10, 8))
sns.heatmap(corr, annot=True, fmt='.2f', cmap='coolwarm', center=0,
            xticklabels=['Янв', 'Фев', 'Мар', 'Апр', 'Май', 'Июн',
                         'Июл', 'Авг', 'Сен', 'Окт', 'Ноя', 'Дек'],
            yticklabels=['Янв', 'Фев', 'Мар', 'Апр', 'Май', 'Июн',
                         'Июл', 'Авг', 'Сен', 'Окт', 'Ноя', 'Дек'],
            linewidths=0.5, cbar_kws={'label': 'Коэффициент корреляции'})
plt.title('Корреляция между месяцами по количеству терактов', fontsize=16)
plt.xlabel('Месяц')
plt.ylabel('Месяц')
plt.tight_layout()
plt.show()

# Анализ результатов
