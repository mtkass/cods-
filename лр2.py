# Шаг 2. Получаем агрегированные данные по странам
cur.execute("""
    SELECT country_txt, COUNT(*) as cnt
    FROM terrorist_attacks
    GROUP BY country_txt
    ORDER BY cnt;
""")
country_data = cur.fetchall()

if len(country_data) < 10:
    print("Слишком мало стран для анализа")
else:
    countries = [row[0] for row in country_data]
    counts = [row[1] for row in country_data]

    total_range = max(counts) - min(counts)
    threshold_10 = total_range * 0.1
    print(f"Общий размах: {total_range}, 10% = {threshold_10:.2f}")

    n = len(counts)
    left_10_end = int(n * 0.1)
    right_10_start = int(n * 0.9)

    to_delete = set()

    # Шаг 3. Ищем разрыв в левой части
    for i in range(left_10_end - 1, 0, -1):
        diff = counts[i] - counts[i-1]
        if diff > threshold_10:
            print(f"Найден разрыв в левой части: {counts[i-1]} → {counts[i]} = {diff:.2f}")
            to_delete.update(countries[:i+1])
            break

    # Шаг 4. Ищем разрыв в правой части
    for i in range(right_10_start, n-1):
        diff = counts[i+1] - counts[i]
        if diff > threshold_10:
            print(f"Найден разрыв в правой части: {counts[i]} → {counts[i+1]} = {diff:.2f}")
            to_delete.update(countries[i+1:])
            break

    # Шаг 5. Удаляем найденные страны
    if to_delete:
        delete_list = list(to_delete)
        batch_size = 50
        for i in range(0, len(delete_list), batch_size):
            batch = delete_list[i:i+batch_size]
            placeholders = ','.join(['%s'] * len(batch))
            cur.execute(f"""
                DELETE FROM terrorist_attacks
                WHERE country_txt IN ({placeholders});
            """, batch)
        conn.commit()
        print(f"Удалено строк из экстремальных стран: {cur.rowcount}")
    else:
        print("Экстремальных стран не найдено")

